// Generates src/shared/widgets/region-map/regionPaths.ts for the region picker:
// one filled outline per game continent,
// from Natural Earth 1:110m (world-atlas). Countries are grouped by the
// continent the country catalog assigns them, so the map matches gameplay
// (for example, the catalog counts all of Russia as Europe).
//
// Run: node apps/web/scripts/build-region-map.mjs
import { geoEqualEarth, geoPath } from 'd3-geo'
import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { feature, merge } from 'topojson-client'

const require = createRequire(import.meta.url)
const here = path.dirname(fileURLToPath(import.meta.url))
const topology = require('world-atlas/countries-110m.json')
const registry = JSON.parse(
	fs.readFileSync(
		path.join(
			here,
			'../../../packages/country-catalog/generated/countries.registry.json',
		),
		'utf8',
	),
)

const WIDTH = 800
/** Rotating 11° east puts the map's seam in the Bering Strait, not Siberia. */
const ROTATION = [-11, 0]
const MIN_AREA_PX = 3
const CONTINENTS = [
	'africa',
	'asia',
	'europe',
	'north-america',
	'oceania',
	'south-america',
]

const continentById = new Map(registry.countries.map(c => [c.id, c.continent]))
// Natural Earth shapes without an ISO code, assigned to their neighbours' continent.
const CONTINENT_BY_NAME = {
	Kosovo: 'europe',
	Somaliland: 'africa',
	'N. Cyprus': 'asia',
}
const continentOf = geometry =>
	continentById.get(geometry.id) ??
	CONTINENT_BY_NAME[geometry.properties?.name]

const allGeometries = topology.objects.countries.geometries
const geometries = allGeometries.filter(
	g => continentOf(g) && continentOf(g) !== 'antarctica',
)
const unmatched = allGeometries
	.filter(g => !continentOf(g))
	.map(g => `${g.id ?? '?'} ${g.properties?.name ?? ''}`)

const land = feature(topology, { type: 'GeometryCollection', geometries })
const projection = geoEqualEarth().rotate(ROTATION).fitWidth(WIDTH, land)
const toPath = geoPath(projection)
const [[, y0], [, y1]] = toPath.bounds(land)
const [tx, ty] = projection.translate()
projection.translate([tx, ty - y0])
const height = Math.ceil(y1 - y0)

function withoutSpecks(shape) {
	const polygons =
		shape.type === 'Polygon' ? [shape.coordinates] : shape.coordinates
	return {
		type: 'MultiPolygon',
		coordinates: polygons.filter(
			coordinates =>
				toPath.area({ type: 'Polygon', coordinates }) >= MIN_AREA_PX,
		),
	}
}

const round = d =>
	d.replace(/-?\d+\.\d+/g, n => String(Math.round(Number(n) * 10) / 10))

const fills = Object.fromEntries(
	CONTINENTS.map(continent => [
		continent,
		round(
			toPath(
				withoutSpecks(
					merge(
						topology,
						geometries.filter(g => continentOf(g) === continent),
					),
				),
			),
		),
	]),
)

const out = `// Generated by apps/web/scripts/build-region-map.mjs. Do not edit by hand.
// Natural Earth 1:110m outlines (public domain) via world-atlas.
import type { GameContinent } from '@georally/game-domain'

export const REGION_MAP_VIEWBOX = '0 0 ${WIDTH} ${height}'

export const REGION_PATHS: Record<Exclude<GameContinent, 'antarctica'>, string> = ${JSON.stringify(fills, null, '\t')}

`
const target = path.join(
	here,
	'../src/shared/widgets/region-map/regionPaths.ts',
)
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, out)
console.log(
	`wrote ${path.relative(process.cwd(), target)} (${(out.length / 1024).toFixed(1)} KiB)`,
)
if (unmatched.length) console.log('not in catalog:', unmatched.join(', '))
